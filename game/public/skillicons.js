const cache = {};
/** A 16×16 canvas for one skill id; unknown ids get an empty one. */
export function skillIcon(id) {
  if (cache[id]) return cache[id];
  const c = document.createElement("canvas");
  c.width = c.height = 16;
  const g = c.getContext("2d");
  const rows = GLYPH[id] || [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (ch === "#" || ch === "o") { g.fillStyle = ch === "#" ? LIGHT : DIM; g.fillRect(x, y, 1, 1); }
    }
  });
  return (cache[id] = c);
}
const urls = {};
export const skillIconUrl = (id) => urls[id] || (urls[id] = skillIcon(id).toDataURL());
/** Rows that are not sixteen wide, for the preview page to complain about. */
export function badRows() {
  const out = [];
  for (const id of Object.keys(GLYPH)) GLYPH[id].forEach((r, y) => { if (r.length !== 16 || GLYPH[id].length !== 16) out.push(`${id}:${y}:${r.length}`); });
  return out;
}
export const ALL = Object.keys(GLYPH);
