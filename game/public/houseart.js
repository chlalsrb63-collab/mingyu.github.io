/** A furniture icon (16×16 canvas), or null for an id that has none. */
export function furnIcon(id) {
  const rows = ICON[id];
  if (!rows) return null;
  const c = document.createElement("canvas");
  c.width = c.height = 16;
  const g = c.getContext("2d");
  const on = (x, y) => x >= 0 && y >= 0 && x < 16 && y < 16 && rows[y][x] !== ".";
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const ch = rows[y][x];
    if (ch === ".") {
      // the ink outline: every empty pixel that touches a filled one
      if (on(x - 1, y) || on(x + 1, y) || on(x, y - 1) || on(x, y + 1)) { g.fillStyle = INK; g.fillRect(x, y, 1, 1); }
      continue;
    }
    g.fillStyle = PAL[ch] || INK;
    g.fillRect(x, y, 1, 1);
  }
  return c;
}
