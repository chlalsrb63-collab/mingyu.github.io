#!/usr/bin/env node
// Builds src/logic.js from the ordered fragments in src/logic/*.js and the editor's data
// files in data/ (docs/editor/SCHEMA.md).
//
// The fragments are NOT modules: they share one scope and are simply
// concatenated in filename order (00-…, 10-…, …, 90-…). The deploy target needs
// one import-free logic.js, so that file is generated and committed. The data
// files become one more, generated, fragment right after 00-header:
// `const DATA = { maps: [...], links: [...], npcs: [...], quests: { main, side } };`
//
//   node scripts/build-logic.mjs           rebuild src/logic.js (writes only if changed)
//   node scripts/build-logic.mjs --check   exit 1 if src/logic.js is stale or a rule is broken
//   node scripts/build-logic.mjs --watch   rebuild whenever a fragment or a data file changes
//
// Importable (the editor server and scripts/editor-lib.mjs use it):
//   readData(dataDir?)            → { data, problems }   the data files, read and lightly checked
//   buildLogic({ dataDir?, data? }) → { text, files, problems }   the logic.js text it would write
//
// Pure node, no dependencies; works the same on Windows and POSIX.
import { readFileSync, writeFileSync, readdirSync, existsSync, watch, statSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PARTS = join(ROOT, "src", "logic");
const OUT = join(ROOT, "src", "logic.js");
export const DATA_DIR = join(ROOT, "data");

const HEADER =
  "// GENERATED — edit src/logic/*.js (and data/**), then run npm run build:logic\n" +
  "// (do not edit this file by hand: npm run check:split fails when it is stale)\n";

// Determinism and deploy rules for the shared rules scope. Comments are not
// stripped, so keep these words out of comments too.
const FORBIDDEN = [
  [/^\s*import[\s{*"']/m, "no import statements (the deploy target needs one self-contained file)"],
  [/\brequire\s*\(/, "no require()"],
  [/\bMath\.random\b/, "no Math.random — use rnd(box) / ri(box, a, b)"],
  [/\bDate\.now\b|\bnew Date\b|\bperformance\.now\b/, "no clock reads — use the `now` the room passes in"],
];

const lf = (s) => s.replace(/\r\n?/g, "\n");
const isObj = (v) => typeof v === "object" && v !== null && !Array.isArray(v);

function partFiles() {
  return readdirSync(PARTS).filter((f) => /^\d\d-[\w-]+\.js$/.test(f)).sort();
}

/** The empty data set: the game exactly as it is without the editor. */
export const EMPTY_DATA = () => ({ maps: [], links: [], npcs: [], quests: { main: null, side: [] } });

function readJson(file, problems) {
  try {
    let s = readFileSync(file, "utf8");
    if (s.charCodeAt(0) === 0xfeff) s = s.slice(1);
    return JSON.parse(s);
  } catch (e) {
    problems.push(`${file}: JSON을 읽을 수 없습니다 (${e.message})`);
    return null;
  }
}

/**
 * Read data/** (sorted, so the result is the same on every machine). Only the shape the
 * rules rely on is checked here; scripts/data-check.mjs does the full validation.
 */
export function readData(dataDir = DATA_DIR) {
  const data = EMPTY_DATA(), problems = [];
  if (!existsSync(dataDir)) return { data, problems };
  const rel = (f) => f.slice(dataDir.length + 1).replace(/\\/g, "/");
  const mapsDir = join(dataDir, "maps");
  if (existsSync(mapsDir)) {
    const seen = new Set();
    for (const f of readdirSync(mapsDir).filter((f) => f.endsWith(".json")).sort()) {
      const file = join(mapsDir, f), m = readJson(file, problems);
      if (!m) continue;
      const where = `data/${rel(file)}`;
      if (!isObj(m) || typeof m.id !== "string" || !/^[a-z][a-z0-9_]{1,23}$/.test(m.id)) { problems.push(`${where}: "id"가 올바르지 않습니다`); continue; }
      if (seen.has(m.id)) { problems.push(`${where}: 지도 id "${m.id}"가 중복됩니다`); continue; }
      const w = m.w, h = m.h;
      if (!Number.isInteger(w) || !Number.isInteger(h) || w < 16 || h < 16 || w > 160 || h > 160) { problems.push(`${where}: 크기(w, h)는 16..160 정수여야 합니다`); continue; }
      const grid = (k) => Array.isArray(m[k]) && m[k].length === h && m[k].every((r) => typeof r === "string" && r.length === w);
      if (!grid("ground") || !grid("objects")) { problems.push(`${where}: ground/objects는 ${w}글자 × ${h}줄이어야 합니다`); continue; }
      seen.add(m.id);
      data.maps.push(m);
    }
  }
  const list = (name, key) => {
    const file = join(dataDir, name);
    if (!existsSync(file)) return [];
    const j = readJson(file, problems);
    if (!j) return [];
    if (!isObj(j) || !Array.isArray(j[key])) { problems.push(`data/${name}: "${key}" 배열이 없습니다`); return []; }
    return j[key].filter(isObj);
  };
  data.links = list("links.json", "links");
  data.npcs = list("npcs.json", "npcs");
  const qf = join(dataDir, "quests.json");
  if (existsSync(qf)) {
    const q = readJson(qf, problems);
    if (q && !isObj(q)) problems.push("data/quests.json: 객체여야 합니다");
    else if (q) {
      if (q.main !== null && q.main !== undefined && !Array.isArray(q.main)) problems.push('data/quests.json: "main"은 null 또는 배열이어야 합니다');
      else data.quests.main = Array.isArray(q.main) && q.main.length ? q.main.filter(isObj) : null;
      data.quests.side = Array.isArray(q.side) ? q.side.filter(isObj) : [];
    }
  }
  return { data, problems };
}

/** The generated fragment: one line per map, so a diff of logic.js shows which map changed. */
function dataPart(data) {
  const j = (v) => JSON.stringify(v);
  let s = "// ───────────────────────────── editor data (GENERATED from data/**) ─────────────────────────────\n";
  s += "/** Maps, doors, NPCs and quests made in the world map editor (docs/editor/SCHEMA.md). */\n";
  s += "const DATA = {\n  maps: [\n";
  for (const m of data.maps) s += `    ${j(m)},\n`;
  s += "  ],\n";
  s += `  links: ${j(data.links)},\n  npcs: ${j(data.npcs)},\n  quests: ${j(data.quests)},\n};\n`;
  return s;
}

/** The logic.js text for these fragments and this data (data defaults to data/**). */
export function buildLogic(opts = {}) {
  const files = partFiles();
  if (!files.length) throw new Error(`no fragments found in ${PARTS}`);
  const problems = [];
  let data = opts.data;
  if (!data) {
    const r = readData(opts.dataDir || DATA_DIR);
    data = r.data;
    problems.push(...r.problems);
  }
  let body = "";
  for (const f of files) {
    let src = lf(readFileSync(join(PARTS, f), "utf8"));
    if (src.charCodeAt(0) === 0xfeff) src = src.slice(1); // stray BOM from a Windows editor
    if (!src.endsWith("\n")) src += "\n"; // never glue the last line onto the next fragment
    for (const [re, why] of FORBIDDEN) {
      const m = re.exec(src);
      if (m) {
        const line = src.slice(0, m.index).split("\n").length;
        problems.push(`src/logic/${f}:${line}: ${why}`);
      }
    }
    body += src;
    if (f.startsWith("00-")) body += dataPart(data);
  }
  return { text: HEADER + body, files, problems };
}

function run(mode) {
  const { text, files, problems } = buildLogic();
  if (problems.length) {
    console.error("logic fragments or data files break a rule:\n  " + problems.join("\n  "));
    return 1;
  }
  const have = existsSync(OUT) ? lf(readFileSync(OUT, "utf8")) : null;
  const lines = text.split("\n").length - 1;
  if (mode === "check") {
    if (have !== text) {
      console.error("src/logic.js is stale: it does not match src/logic/*.js and data/**. Run: npm run build:logic");
      return 1;
    }
    console.log(`src/logic.js is up to date (${files.length} fragments + data, ${lines} lines).`);
    return 0;
  }
  if (have === text) {
    console.log(`src/logic.js unchanged (${files.length} fragments + data, ${lines} lines).`);
  } else {
    writeFileSync(OUT, text);
    console.log(`src/logic.js rebuilt from ${files.length} fragments + data (${lines} lines).`);
  }
  return 0;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  if (args.includes("--watch")) {
    run("build");
    let timer = null;
    const again = () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        try { run("build"); } catch (e) { console.error(e.message); }
      }, 120);
    };
    watch(PARTS, again);
    for (const d of [DATA_DIR, join(DATA_DIR, "maps")]) if (existsSync(d) && statSync(d).isDirectory()) watch(d, again);
    console.log("watching src/logic/ and data/ … (Ctrl+C to stop)");
  } else {
    process.exitCode = run(args.includes("--check") ? "check" : "build");
  }
}
